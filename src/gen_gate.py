"""
gen_gate: generate a no_std Rust (f32) gate from a .bio specification (transition-first semantics).

  python gen_gate.py examples/drone_shield_v2.bio gate_rv32/src/main.rs

Every comparison keeps its written direction and is evaluated with IEEE-754 f32 semantics (a comparison with NaN is false).
DISTANCE(a, b) <op> T is compiled as d2 <op> T*T with d2 = (ax-bx)^2 + (ay-by)^2 (no square root); only comparisons of DISTANCE with a numeric
constant T >= 0 are supported, anything else is rejected.
The generated function  gate_step(state, gps_x, gps_y, ins_x, ins_y, rf) -> (next_state | alarm << 8)  is exported with the C ABI.
A state value outside the declared range (memory corruption) is treated fail-safe: it moves to the SAFETY_LOCK state (or the last state).
"""
import sys
from bio_subset import parse, BioError


def f32lit(v):
    s = repr(float(v))
    return s + "f32" if "e" not in s else s + "_f32"


class Gen:
    def __init__(self, cell):
        self.cell = cell
        self.vec = {n for n, t in cell["inputs"].items() if t == "VECTOR2D"}
        self.scal = [n for n, t in cell["inputs"].items() if t == "FLOAT"]
        self.d2 = {}      # (a, b) -> variable name

    def d2var(self, a, b):
        key = (a, b)
        if key not in self.d2: self.d2[key] = f"d2_{len(self.d2)}"
        return self.d2[key]

    def num(self, e):
        if e[0] == "num": return f32lit(e[1])
        if e[0] == "neg": return "(-" + self.num(e[1]) + ")"
        if e[0] == "id":
            if e[1] in self.scal: return e[1]
            raise BioError(f"identifier {e[1]} is not a scalar input")
        raise BioError("unsupported numeric expression " + str(e))

    def const(self, e):
        if e[0] == "num": return e[1]
        if e[0] == "neg" and e[1][0] == "num": return -e[1][1]
        raise BioError("DISTANCE must be compared with a numeric constant")

    def boolean(self, e):
        k = e[0]
        if k == "not": return "!(" + self.boolean(e[1]) + ")"
        if k == "bin":
            op = e[1]
            if op == "AND": return "(" + self.boolean(e[2]) + " && " + self.boolean(e[3]) + ")"
            if op == "OR": return "(" + self.boolean(e[2]) + " || " + self.boolean(e[3]) + ")"
            if op in (">", "<", ">=", "<=", "==", "!="):
                l, r = e[2], e[3]
                if l[0] == "call":
                    if l[1] != "DISTANCE" or len(l[2]) != 2 or l[2][0][0] != "id" or l[2][1][0] != "id": raise BioError("unsupported call")
                    a, b = l[2][0][1], l[2][1][1]
                    if a not in self.vec or b not in self.vec: raise BioError("DISTANCE needs VECTOR2D inputs")
                    T = self.const(r)
                    if T < 0: raise BioError("negative distance limit")
                    return f"({self.d2var(a, b)} {op} {f32lit(T * T)})"
                return f"({self.num(l)} {op} {self.num(r)})"
        raise BioError("unsupported boolean expression " + str(e))


def generate(cell):
    g = Gen(cell); names = [s["name"] for s in cell["states"]]
    lock = next((i for i, s in enumerate(cell["states"]) if s["type"] == "SAFETY_LOCK"), len(names) - 1)
    arms, outs = [], []
    for i, s in enumerate(cell["states"]):
        body = ""
        for tgt, guard in s["trans"]:
            body += f"            if {g.boolean(guard)} {{ next = {names.index(tgt)}; }}\n" if not body else f"            else if {g.boolean(guard)} {{ next = {names.index(tgt)}; }}\n"
        arms.append(f"        {i} => {{\n{body}        }}  // {s['name']}\n")
        assign = dict(s["assigns"]).get("alarm")
        if assign is None: raise BioError(f"state {s['name']} does not assign alarm")
        val = g.num(assign)
        outs.append(f"        {i} => {int(float(assign[1])) if assign[0] == 'num' else val},  // {s['name']}\n")
    vecs = sorted(g.vec)
    args = ", ".join([f"{v}_x: f32, {v}_y: f32" for v in vecs] + [f"{n}: f32" for n in g.scal])
    d2lines = "".join(f"    let dx = {a}_x - {b}_x; let dy = {a}_y - {b}_y; let {var} = dx * dx + dy * dy;\n" if i == 0 else
                      f"    let dx = {a}_x - {b}_x; let dy = {a}_y - {b}_y; let {var} = dx * dx + dy * dy;\n" for i, ((a, b), var) in enumerate(g.d2.items()))
    return f'''//! GENERATED by gen_gate.py from {cell["name"]} (do not edit). IEEE-754 f32, no heap, no recursion, no loops.
#![no_std]
#![no_main]
use core::panic::PanicInfo;

#[panic_handler]
fn panic(_: &PanicInfo) -> ! {{ loop {{}} }}

core::arch::global_asm!(".section .text.init", ".global _start", "_start:", "la sp, _stack_top", "1: j 1b");

pub const LOCK_STATE: u32 = {lock};

/// returns next_state | (alarm << 8)
#[no_mangle]
pub extern "C" fn gate_step(state: u32, {args}) -> u32 {{
{d2lines}    let mut next = state;
    match state {{
{"".join(arms)}        _ => {{ next = LOCK_STATE; }}
    }}
    let alarm: u32 = match next {{
{"".join(outs)}        _ => 1,
    }};
    next | (alarm << 8)
}}
'''


if __name__ == "__main__":
    cell = parse(open(sys.argv[1], encoding="utf-8").read())
    open(sys.argv[2], "w", encoding="utf-8").write(generate(cell))
    print("generated", sys.argv[2], "from", cell["name"])
